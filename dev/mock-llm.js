// Tiny OpenAI-compatible mock so the whole pipeline can be exercised without a real key.
function reply(messages) {
  const u = messages[messages.length - 1].content;
  const n = (re) => (u.match(re) || [])[1];
  if (u.includes('Build the world to simulate')) {
    const rounds = Number(n(/exactly (\d+) short events/)) || 3;
    return JSON.stringify({
      product: { name: 'DemoGateway', summary: 'A gateway for AI coding with logging and routing.', claims: ['Lower inference cost (vendor claim)', 'PII redaction'] },
      segments: [{ name: 'Engineering leaders', description: 'CTOs', pains: ['spend', 'audit'], buying_role: 'buyer', share: 0.5 }, { name: 'Developers', description: 'daily users', pains: ['limits'], buying_role: 'user', share: 0.3 }, { name: 'Security', description: 'CISO team', pains: ['PII'], buying_role: 'blocker', share: 0.2 }],
      competitors: ['Copilot', 'Cursor'], tensions: ['cost vs quality', 'control vs convenience'],
      events: ['Outreach lands', 'Competitor cuts price', 'Privacy news', 'Outage'].slice(0, rounds),
    });
  }
  if (u.includes('Create ') && u.includes('distinct simulated people')) {
    const ids = [...u.matchAll(/a(\d+) = ([^;\n]+?)(?:;|\. Within)/g)].map((x) => [+x[1], x[2].trim()]);
    const a = ids[0][0], b = ids[ids.length - 1][0];
    const roles = ['champion', 'blocker', 'decider', 'influencer', 'user'];
    const segs = ['Engineering leaders', 'Developers', 'Security'];
    const agents = [];
    for (let i = a; i <= b; i++) agents.push({ id: 'a' + i, name: 'Person ' + i, segment: (ids.find((x) => x[0] === i) || [0, segs[i % 3]])[1], role: roles[i % 5], bio: 'Mock bio ' + i, current_tools: ['Cursor'], pain: 'spend', skepticism: (i % 5) + 1, price_sensitivity: 'high' });
    return JSON.stringify({ agents });
  }
  if (u.includes('PEOPLE ACTING THIS ROUND')) {
    const ids = [...u.matchAll(/^- (a\d+) /gm)].map((x) => x[1]);
    return JSON.stringify({ actions: ids.map((id, i) => ({ agent_id: id, action: i % 4 === 3 ? 'ignore' : i % 2 ? 'reply' : 'post', text: `Mock take from ${id}: interesting but I need proof.`, reply_to: null, stance: ((+id.slice(1) + i) % 5) - 2, intent: ['adopt', 'trial', 'wait', 'reject'][i % 4], objection: ['cost', 'trust', 'proof', 'none'][i % 4] })) });
  }
  if (u.includes('Answer as yourself')) return JSON.stringify({ answers: ['Mock answer one.', 'Mock answer two.', 'Mock answer three.'] });
  if (u.includes('executive summary')) return JSON.stringify({ bottom_line: 'Mock bottom line.', who_will_buy: ['Mock buyer'], who_will_resist: ['Mock blocker'], biggest_risk: 'Mock risk.', do_first: ['One', 'Two', 'Three'] });
  if (u.includes('"verdict_reason"')) return JSON.stringify({ title: 'Mock finding: proof beats price', summary: 'Mock summary.', verdict: 'Go with changes', verdict_reason: 'Mock reason.' });
  if (u.includes('CHAPTER:')) return `**Mock lead-in.** This chapter is generated by the mock model.\n\n> "Mock quote." — Person 1, Developers (simulated)\n\n- point one\n- point two`;
  if (u.includes('Say hi')) return 'hi';
  return '{}';
}
module.exports = { reply };
